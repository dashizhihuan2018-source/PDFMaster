// Windows-owned, operation-specific page input. No web form fallback.
#[cfg(not(windows))]
pub(super) async fn prompt(
    _: &tauri::AppHandle,
    _: &str,
    _: &str,
) -> Result<Option<String>, String> {
    Err("页码输入仅支持 Windows 原生窗口。".into())
}

#[cfg(windows)]
pub(super) async fn prompt(
    app: &tauri::AppHandle,
    title: &str,
    label: &str,
) -> Result<Option<String>, String> {
    use tauri::Manager;
    let parent = app
        .get_webview_window("main")
        .ok_or("页码输入窗口不存在")?
        .hwnd()
        .map_err(|e| e.to_string())?
        .0 as isize;
    let title = title.to_owned();
    let label = label.to_owned();
    let (tx, rx) = tokio::sync::oneshot::channel();
    app.run_on_main_thread(move || {
        let _ = tx.send(native::show(parent, &title, &label));
    })
    .map_err(|e| e.to_string())?;
    rx.await
        .map_err(|_| "Windows 页码输入窗口不可用。".to_string())?
}

#[cfg(windows)]
mod native {
    use windows_sys::Win32::{
        Foundation::*,
        System::LibraryLoader::GetModuleHandleW,
        UI::{Input::KeyboardAndMouse::SetFocus, WindowsAndMessaging::*},
    };
    const INPUT: i32 = 100;
    const LIMIT: usize = 2048;
    // DWLP_USER is a C-header pointer-size macro, not generated by windows-sys.
    const DWLP_USER: i32 = (2 * std::mem::size_of::<isize>()) as i32;
    struct Input {
        result: Option<String>,
    }
    fn word(out: &mut Vec<u16>, value: u32) {
        out.push(value as u16);
        out.push((value >> 16) as u16);
    }
    fn text(out: &mut Vec<u16>, value: &str) {
        out.extend(value.encode_utf16());
        out.push(0);
    }
    // DLGTEMPLATE and DLGITEMTEMPLATE require DWORD alignment; Vec<u32>
    // provides it for the final buffer, with no borrowed unaligned structure.
    #[allow(clippy::too_many_arguments)]
    fn control(
        out: &mut Vec<u16>,
        style: u32,
        x: u16,
        y: u16,
        w: u16,
        h: u16,
        id: u16,
        class: u16,
        label: &str,
    ) {
        if !out.len().is_multiple_of(2) {
            out.push(0);
        }
        word(out, WS_CHILD | WS_VISIBLE | style);
        word(out, 0);
        out.extend([x, y, w, h, id, 0xffff, class]);
        text(out, label);
        out.push(0);
    }
    unsafe extern "system" fn dialog(hwnd: HWND, msg: u32, wp: WPARAM, lp: LPARAM) -> isize {
        unsafe {
            match msg {
                WM_INITDIALOG => {
                    SetWindowLongPtrW(hwnd, DWLP_USER, lp);
                    SendDlgItemMessageW(hwnd, INPUT, 0x00c5, LIMIT, 0); // EM_LIMITTEXT
                    SetFocus(GetDlgItem(hwnd, INPUT));
                    0
                }
                WM_COMMAND => match wp as u16 as i32 {
                    IDOK => {
                        let ptr = GetWindowLongPtrW(hwnd, DWLP_USER) as *mut Input;
                        if !ptr.is_null() {
                            let mut buffer = vec![0u16; LIMIT + 1];
                            let n = GetDlgItemTextW(
                                hwnd,
                                INPUT,
                                buffer.as_mut_ptr(),
                                buffer.len() as i32,
                            ) as usize;
                            (*ptr).result = Some(String::from_utf16_lossy(&buffer[..n]));
                        }
                        EndDialog(hwnd, IDOK as isize);
                        1
                    }
                    IDCANCEL => {
                        EndDialog(hwnd, IDCANCEL as isize);
                        1
                    }
                    _ => 0,
                },
                WM_CLOSE => {
                    EndDialog(hwnd, IDCANCEL as isize);
                    1
                }
                _ => 0,
            }
        }
    }
    pub(super) fn show(parent: isize, title: &str, label: &str) -> Result<Option<String>, String> {
        let mut v = Vec::new();
        word(
            &mut v,
            WS_POPUP
                | WS_CAPTION
                | WS_SYSMENU
                | DS_MODALFRAME as u32
                | DS_SETFONT as u32
                | DS_CENTER as u32,
        );
        word(&mut v, 0);
        v.extend([4, 0, 0, 260, 100, 0, 0]);
        text(&mut v, title);
        v.push(9);
        text(&mut v, "Segoe UI");
        control(&mut v, 0, 12, 10, 236, 16, 101, 0x82, label);
        control(
            &mut v,
            WS_BORDER | WS_TABSTOP | 0x80,
            12,
            30,
            236,
            18,
            INPUT as u16,
            0x81,
            "",
        ); // ES_AUTOHSCROLL
        control(
            &mut v,
            WS_TABSTOP | 1,
            116,
            66,
            62,
            22,
            IDOK as u16,
            0x80,
            "确定",
        ); // BS_DEFPUSHBUTTON
        control(
            &mut v,
            WS_TABSTOP,
            186,
            66,
            62,
            22,
            IDCANCEL as u16,
            0x80,
            "取消",
        );
        if v.len() % 2 != 0 {
            v.push(0);
        }
        let aligned: Vec<u32> = v
            .chunks_exact(2)
            .map(|w| w[0] as u32 | ((w[1] as u32) << 16))
            .collect();
        let mut input = Input { result: None };
        // SAFETY: aligned template and Input remain alive throughout the
        // synchronous owned modal loop. Windows handles Enter/Escape/tab order.
        let result = unsafe {
            DialogBoxIndirectParamW(
                GetModuleHandleW(std::ptr::null()),
                aligned.as_ptr().cast(),
                parent as HWND,
                Some(dialog),
                &mut input as *mut Input as isize,
            )
        };
        if result == -1 {
            Err(format!("Windows 页码输入失败：{}", unsafe {
                GetLastError()
            }))
        } else {
            Ok(input.result)
        }
    }
}
